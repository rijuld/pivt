import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import * as topojson from "topojson-client";
import { geoEquirectangular, geoPath } from "d3-geo";
import land110 from "world-atlas/land-110m.json" with { type: "json" };

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const W = 720;
const H = 360;

const land = topojson.feature(land110, land110.objects.land);
const projection = geoEquirectangular().fitExtent(
  [
    [0, 0],
    [W, H],
  ],
  land,
);
const pathGen = geoPath(projection);
const d = pathGen(land);

if (!d) {
  console.error("Empty path");
  process.exit(1);
}

const outPath = path.join(root, "src/lib/world-land-equirect-path.ts");
const body = `/** Natural Earth 110m land — equirectangular SVG path for ${W}×${H} viewBox. Generated by scripts/generate-world-land-path.mjs */
export const WORLD_LAND_PATH_D = ${JSON.stringify(d)} as const;
`;

fs.writeFileSync(outPath, body, "utf8");
console.log("Wrote", outPath, "path length", d.length);
